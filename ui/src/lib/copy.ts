export type Copy = typeof copy;

/** Fills {name} placeholders. Unknown placeholders are left as they are, so a typo shows up on screen. */
export function fmt(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (all, key: string) => (key in vars ? String(vars[key]) : all));
}

const pct = (n: number): number => Math.round(n);

export const unsaved = (n: number): string => (n === 1 ? copy.save.one : fmt(copy.save.many, { n }));
export const stepsOf = (n: number, max: number): string => fmt(copy.light.stepsOf, { n, max });
export const stepN = (n: number): string => fmt(copy.light.stepN, { n });
export const tilt = (p: number): string => fmt(copy.stick.tilt, { n: pct(p) });
export const gives = (t: number, out: number): string => fmt(copy.stick.gives, { a: pct(t), b: pct(out) });
export const memoryUsed = (p: number): string => fmt(copy.script.memory, { n: pct(p) });
export const onButton = (button: string): string => fmt(copy.script.on, { button });
export const copiedTo = (slot: number): string => fmt(copy.profile.copied, { n: slot });
export const devicePill = (mode: string): string => fmt(copy.top.device, { mode });
export const minutes = (n: number): string => fmt(copy.settings.minutes, { n });
export const slotLabel = (slot: number): string => fmt(copy.slots.label, { n: slot + 1 });
export const macrosUsed = (n: number, max: number): string => fmt(copy.button.macrosUsed, { n, max });
export const barName = (button: string, from: number, to: number): string => fmt(copy.script.bar, { button, from, to });
export const barRange = (from: number, to: number): string => fmt(copy.script.range, { from, to });
